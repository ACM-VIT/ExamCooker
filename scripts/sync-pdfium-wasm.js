#!/usr/bin/env node

const crypto = require("crypto");
const fs = require("fs");
const path = require("path");

const sourcePath = require.resolve("@embedpdf/pdfium/pdfium.wasm");
const outputPath = path.join(
  __dirname,
  "..",
  "public",
  "vendor",
  "embedpdf",
  "pdfium.wasm",
);

function sha256(filePath) {
  return crypto.createHash("sha256").update(fs.readFileSync(filePath)).digest("hex");
}

fs.mkdirSync(path.dirname(outputPath), { recursive: true });

const sourceHash = sha256(sourcePath);
const versionedUrl = `/vendor/embedpdf/immutable/${sourceHash}.wasm`;
const versionedPath = path.join(__dirname, "..", "public", versionedUrl);

// Retain the legacy URL for older clients, but only immutable, content-addressed
// URLs may skip browser revalidation. The package bytes determine the URL.
for (const destination of [outputPath, versionedPath]) {
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  if (!fs.existsSync(destination) || sha256(destination) !== sourceHash) {
    fs.copyFileSync(sourcePath, destination);
  }
}

const metadataPath = path.join(__dirname, "..", "lib", "generated", "pdfium-wasm.ts");
const metadata = `// Generated by scripts/sync-pdfium-wasm.js from the installed PDFium package.\nexport const PDFIUM_WASM_URL = ${JSON.stringify(versionedUrl)};\n`;
fs.mkdirSync(path.dirname(metadataPath), { recursive: true });
if (!fs.existsSync(metadataPath) || fs.readFileSync(metadataPath, "utf8") !== metadata) {
  fs.writeFileSync(metadataPath, metadata);
}
console.log(`PDFium assets ready (${sourceHash})`);
