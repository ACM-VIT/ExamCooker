import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const css = readFileSync(
  new URL("app/components/common/catalog-appearance.css", root),
  "utf8",
);
const logo = readFileSync(
  new URL("public/assets/logo-icon.svg", root),
  "utf8",
).replace("<svg ", '<svg aria-hidden="true" class="website-logo" ');
// This existing website asset is the variable font (weights 200–800), despite its filename.
const font = readFileSync(
  new URL("public/assets/fonts/plus-jakarta-sans-bold.woff2", root),
).toString("base64");
const output = new URL("lib/mcp/generated/website-appearance.ts", root);
const content =
  "// Generated by scripts/sync-mcp-ui.mjs. Edit the shared CSS or website assets.\n" +
  "export const EXAMCOOKER_FONT_CSS = " +
  JSON.stringify(
    '@font-face{font-family:"Plus Jakarta Sans";font-style:normal;font-weight:200 800;font-display:swap;src:url(data:font/woff2;base64,' +
      font +
      ') format("woff2")}',
  ) +
  ";\n" +
  "export const EXAMCOOKER_CATALOG_CSS = " +
  JSON.stringify(css) +
  ";\n" +
  "export const EXAMCOOKER_LOGO_SVG = " +
  JSON.stringify(logo) +
  ";\n";
mkdirSync(fileURLToPath(new URL("lib/mcp/generated/", root)), {
  recursive: true,
});
let existing = "";
try {
  existing = readFileSync(output, "utf8");
} catch {}
if (existing !== content) writeFileSync(output, content);
console.log("MCP website font, styles and logo ready");
